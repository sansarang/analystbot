def fill(template: str, **fields: str) -> str:
    """{{KEY}} 만 치환한다. 출력 JSON 예시의 중괄호는 건드리지 않는다."""
    out = template
    for key, value in fields.items():
        out = out.replace("{{" + key + "}}", value)
    return out
