#: 🔴 컵 경기를 가리키는 **대회 이름 조각**(실측 2026-10-12 · fotmob 표기)
#  ⚠️ 목록을 늘릴 때는 **받아서 확인한 글자만** 넣는다(추측 금지).
CUP_WORDS: tuple[str, ...] = ("cup", "컵", "trophy", "shield", "copa",
                              "coppa", "coupe", "pokal", "taça", "beker")

#: 🔴🔴 다른 길 — *"상대 Elo 보정 후 가중 0.5"*. 🔴 **임시값**(백필 적합 전).
