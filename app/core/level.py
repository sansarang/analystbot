CUP_WEIGHT = 0.5


def is_cup(league: str) -> bool:
    """🔴 그 대회가 컵인가 — 이름 조각으로 본다(원본은 `CUP_WORDS`)."""
    said = str(league or "").lower()
    return any(w in said for w in CUP_WORDS)
