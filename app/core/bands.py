"""🔴🔴 **확신 구간 표시** — 사용자 결정 2026-10-12(판정 문턱 **보류**).

> "확신 경기만 판정" 문턱은 **아직 넣지 않는다**. 460경기(상위 20% 58.7%)와
> 라인업 재생 442경기(48.9%)가 크게 달라 **불안정**하다.
> 대신 카드에 **M1 최고 확률이 속한 구간(30/20/10%)만 표시**한다.

🔴 그래서 이 모듈은 **등급에 닿지 않는다** — 글자만 만든다.
⚠️ 경계값은 백필 460경기에서 잰 **M1 최고 확률의 분위**다(2026-10-12):
```
상위 30% 분위 ≥ 0.4480 · 상위 20% ≥ 0.4793 · 상위 10% ≥ 0.5283
```
🔴 그 수를 고치려면 **다시 재서** 고친다(손으로 옮기지 않는다 — 측정 도구는
   `tools/compare_paths.py` 의 선택 적중률 표다).
"""
from __future__ import annotations

#: 🔴 (구간 이름, 최고 확률 문턱) — 큰 것부터
CUTS: tuple[tuple[str, float], ...] = (
    ("상위 10%", 0.5283),
    ("상위 20%", 0.4793),
    ("상위 30%", 0.4480),
)


def of(top: float | None) -> str:
    """🔴 그 최고 확률이 **어느 구간**인가. 밖이면 빈 글자(구간 없음)."""
    if top is None:
        return ""
    for name, cut in CUTS:
        if float(top) >= cut:
            return name
    return ""


def said_of(top: float | None) -> str:
    """🔴 카드 한 줄 — ⚠️ **문턱이 아니다**(판정을 바꾸지 않는다)."""
    if top is None:
        return "⬜ **확신 구간** — 확률이 없다"
    got = of(top)
    if not got:
        return (f"⬜ **확신 구간 밖** — 최고 확률 {float(top):.1%} < "
                f"{CUTS[-1][1]:.1%}(상위 30% 문턱) · ⚠️ 판정 문턱은 **보류**다")
    return (f"🎚 **확신 구간 {got}** — 최고 확률 {float(top):.1%} · "
            f"⚠️ 문턱은 **보류**(표시만 · 460경기와 442경기 표가 크게 달랐다)")
