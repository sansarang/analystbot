from __future__ import annotations

#: 🔴 §7-4 가 **이름으로 댄** 두 종류. ⚠️ 셋째를 지어내지 않는다.
KINDS: tuple[str, ...] = ("uncovered", "underweighted")

#: ⚠️ 못 쟀을 때. 🔴 `None`(실패 아님)과 **다른 값**이다 — *"안 쟀다"* 와
#  *"재 봤는데 실패가 아니다"* 는 다른 말이다(#3 조용한 0 금지).
UNKNOWN = "unknown"

_SAY = {
    "uncovered": ("🔴 **없던 시나리오가 터졌다** — 그 결과를 **아예 못 그렸다**. "
                  "규칙 결함이다(§6-2 가 막으려는 것 · M 계약 후보)"),
    "underweighted": ("⚠️ **죽는 시나리오가 터졌다** — 그릴 줄은 알았고 "
                      "**무게를 낮게 줬다**. 🔴 그 무게를 원장으로 고치지 "
                      "않는다(사용자 지시 2026-10-02: 원장은 **검증에만**)"),
    UNKNOWN: ("⚠️ **못 쟀다** — 덮였는지 아닌지를 기록이 말하지 않는다"
              "(채점 입력이 모자랐다)"),
}


def say(kind: str) -> str:
    """사람이 읽는 줄. 🔴 모르는 종류는 **지어내지 않는다**."""
    return _SAY.get(str(kind or ""), "")


def classify(*, covered: bool | None,
             realized_alive: bool | None) -> str | None:
    """🔴🔴 **수가 정한다** — 사람이 고르지 않는다(§6-b 와 같은 결).

    `covered` 는 *"결과가 어느 시나리오에 있었나"*, `realized_alive` 는 *"그
    시나리오가 그 마켓에서 **살아 있었나**"* 다.

    돌려주는 것:
      `"uncovered"`      덮이지 않았다 — **규칙 결함**
      `"underweighted"`  덮였는데 그 시나리오가 **죽어 있었다** — 무게 문제
      `None`             덮였고 살아 있었다 — **실패가 아니다**
      `"unknown"`        🔴 **못 쟀다**(0 으로 때우지 않는다)
    """
    if covered is None:
        return UNKNOWN
    if not covered:
        return "uncovered"
    if realized_alive is None:
        return UNKNOWN
    return None if realized_alive else "underweighted"


def cost_of(match_key: object, rows: list) -> float | None:
    """🔴 그 경기의 **비용**(USD). ⚠️ 줄이 없으면 `None` — **0 이 아니다.**

    🔴 수는 `solar` 가 이미 줄 단위로 적고 있다(`ledger/cost_{YYYYMM}.jsonl`) —
       여기서는 그 경기 줄만 합친다. **두 번째 계수기를 만들지 않는다**(#1).
    ⚠️ `0` 과 `None` 을 섞으면 *"공짜로 했다"* 와 *"안 쟀다"* 가 한 글자가 된다.
    """
    key = str(match_key or "")
    got = [r for r in (rows or [])
           if isinstance(r, dict) and str(r.get("match") or "") == key]
    if not got:
        return None
    # 🔴🔴 **M49** — 원장이 쓰는 칸 이름은 `usd` 다(`cost_usd` 가 아니다).
    #    ⚠️ 실측 2026-10-04: 내가 `cost_usd` 를 읽어 **늘 0** 이었다 —
    #       이름이 갈리면 그 기록은 있어도 없는 것이다(#1 사본 금지).
    return round(sum(float(r.get("usd") or 0.0) for r in got), 6)
