"""🔴🔴 **v5 §8-5 — 표시를 단 상태 줄은 카드에 나와야 한다**(조용한 0 금지).

══════════════════════════════════════════════════════════════════
🔴 실측 2026-10-04 — **에이전트 줄이 한 번도 카드에 안 나왔다**
══════════════════════════════════════════════════════════════════

`analyze.gather` 가 경기마다 이 줄을 적는다:

```
states.setdefault(f"에이전트:{team}", _agent_note(...))
```

그런데 카드를 네 번(`bot6`~`bot9`) 돌려도 **그 줄이 없었다.** 까닭:

```python
for key, why in sorted(states.items()):
    if any(w in str(why) for w in ("unknown", "error", "묻지 않는다", "없")):
        cells_.append(...)        # 🔴 그 네 낱말이 **없으면 사라진다**
```

⚠️ 카드가 *"무엇을 보여줄지"* 를 **글자로 짐작**하고 있었다. 🔴 그래서 §3 에이전트
   상태가 **네 번 내내 보이지 않았고**, 나는 그것을 *"도구를 안 꽂아서"* 로 읽을
   뻔했다 — 실제로는 **표시가 안 됐을 뿐**이다.

🔴 CLAUDE.md #3: *"못 잰 칸은 **이름으로** 남기고 카드·보고에 그대로 적는다."*
   → 🔴·⚠️ 를 단 줄은 **우리가 일부러 표시한 것**이다. 그것이 사라지면 안 된다.
"""
from __future__ import annotations


def _limits(states: dict) -> str:
    """🔴 `_limits` 를 **직접** 부른다 — 카드 전체를 렌더하면 다른 블록이
    섞이고, 이 계약이 보는 것은 **상태 줄이 살아남나** 하나다."""
    from app import analyze
    return "\n".join(analyze._limits([], None, None, dict(states)))


def test_v5_8_5_표시를_단_줄은_반드시_나온다():
    """🔴🔴 **🔴·⚠️·✅ 는 우리가 일부러 단 것이다** — 사라지면 안 된다.

    ══════════════════════════════════════════════════════════════════
    🔴 **같은 병을 두 번 밟았다**(2026-10-04)
    ══════════════════════════════════════════════════════════════════

    `state_shown` 을 만들고 나서도 **에이전트 줄이 또 사라졌다** — 내가 그
    줄을 `✅ §3 에이전트 — …` 로 시작했고 `✅` 가 표시 목록에 **없었다.**
    🔴 §11-1: 같은 꼴 버그가 두 번째면 **그 꼴을 막는 계약**을 쓴다 — 그래서
       이 계약이 **세 표시 전부**를 돌린다.
    """
    got = _limits({
        "에이전트:A": "⚠️ §3 에이전트 **아직 안 돈다** — 도구는 꽂혔다",
        "비용:A": "🔴 예산을 다 썼다",
        "에이전트:B": "✅ §3 에이전트 — 변수 3개",
    })
    assert "에이전트:B" in got, (
        "🔴 `✅` 를 단 줄이 사라졌다 — 그것도 **우리가 일부러 단 표시**다")
    assert "에이전트:A" in got, (
        "🔴 ⚠️ 를 단 상태 줄이 **카드에서 사라졌다** — 카드가 보여줄 것을 "
        "글자로 짐작한다(조용한 0 · CLAUDE.md #3)")
    assert "비용:A" in got, got[-400:]


def test_v5_8_5_옛_네_낱말도_그대로_나온다():
    """⚠️ 종전 기준(`unknown`·`error`·`묻지 않는다`·`없`)을 **깨지 않는다.**"""
    got = _limits({
        "X:1": "unknown", "X:2": "error boom",
        "X:3": "묻지 않는다 — 그 종목이 아니다", "X:4": "자료가 없다",
    })
    for k in ("X:1", "X:2", "X:3", "X:4"):
        assert k in got, (k, got[-300:])


def test_v5_8_5_표시가_없어도_나온다_M50():
    """🔴🔴 **작업 지시서 §1 M50 이 이 계약을 뒤집었다**(2026-10-04).

    > 카드 파이프라인은 **접두 기호로 줄을 거르지 않는다.**

    ⚠️ 종전 이 시험은 *"평범한 성공 줄은 안 나온다"* 를 요구했다. 🔴 그 기준이
       **두 번** 줄을 삼켰다(31줄 · 그리고 고친 뒤에도 에이전트 줄) — 지시서가
       그 기준 자체를 금지했다.
    ⚠️ 카드가 덮이지 않는 까닭은 **`_tally`** 다 — 같은 말을 `×N` 으로 묶는다
       (카탈로그 28줄의 교훈은 그쪽에서 이미 풀렸다).
    """
    got = _limits({"Y:1": "검색 3/3 · 열기 2/2 · 사실 4건"})
    assert "Y:1" in got, got[-300:]


def test_v5_8_5_기준이_한_곳에_있다():
    """🔴 그 판정을 **함수로** 둔다 — 호출부가 글자를 다시 적으면 갈린다(#1)."""
    from app import analyze
    assert callable(getattr(analyze, "state_shown", None)), (
        "🔴 상태 표시 기준이 함수가 아니다 — 글자 목록이 코드에 흩어진다")
    # 🔴 **M50** — 기호·낱말로 고르지 않는다. 글자가 있으면 나온다.
    for said in ("⚠️ 무엇", "🔴 무엇", "✅ 됐다", "unknown",
                 "검색 3/3 · 사실 4건"):
        assert analyze.state_shown(said) is True, said
    # ⚠️ 빈 줄은 **아니다**(적을 것이 없다)
    assert analyze.state_shown("") is False
