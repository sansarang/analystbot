    #  🔴 **13 → 26** — ⑧ 삭제가 끝난 뒤 실측(2026-10-06). 지운 경로의 조항이
    #     계약을 잃었다: 하위 과제 에이전트(§3-*)·검증층 dict 경로(§5-*)·판정
    #     조율(§6-*)·재실행·라이브·원장·게이트. 🔴 v6 가 같은 일을 하는 자리는
