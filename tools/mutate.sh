#!/bin/zsh
# 🔴🔴 **돌연변이 실행기** — §9-5. 복원을 `git checkout` 으로 **구조로** 박는다.
#
# ══════════════════════════════════════════════════════════════════
# 🔴 왜 이 파일이 생겼나 — 사용자 지시 2026-10-04
# ══════════════════════════════════════════════════════════════════
#
# > 같은 함정에 두 번 빠졌으면 규율 한 줄로는 세 번째를 못 막는다. 두 가지를
# > 코드로 박아라. … **돌연변이 복원을 `cp` 가 아니라 `git checkout -- <file>`
# > 로 한다. 복원 뒤 `git diff --quiet` 가 아니면 실패.**
#
# ⚠️ 종전엔 `cp $SP/x.bak app/x.py` 였다. 🔴 그래서 두 가지가 샜다:
#    ① 묵은 `__pycache__` 가 살아 **되돌린 코드가 안 돌았다**(두 번 다쳤다)
#    ② `.bak` 이 **그 시점의 작업 상태**라, 미커밋 변경이 섞이면 무엇이
#       원본인지 알 수 없다
# 🔴 `git checkout` 은 **색인이 원본**이다 — `.bak` 을 들고 다니지 않는다.
#
# 쓰는 법:
#   tools/mutate.sh M64 "짧은 이름을 같은 id 로 안 묶는다" \
#       app/league_index.py 's/찾을것/바꿀것/' tests/contracts/test_x.py …
#
# 🔴 **미커밋 변경이 있으면 거부한다** — `git checkout` 이 그것을 지워 버린다.
set -u
cd "$(git rev-parse --show-toplevel)" || exit 2

NAME=$1; WHY=$2; FILE=$3; EDIT=$4; shift 4
TESTS=("$@")

# ══════════════════════════════════════════════════════════════════
# 🔴 ① 미커밋 변경 금지 — `git checkout` 이 작업을 지운다
# ══════════════════════════════════════════════════════════════════
#  ⚠️ 규율 9 가 `git stash` 를 금지했다(2026-10-04 에 작업을 치웠다). 여기서도
#     치우지 않는다 — **거부하고 사람에게 돌려준다.**
if ! git diff --quiet -- "$FILE"; then
  print -r -- "🔴 $NAME — \`$FILE\` 에 **미커밋 변경**이 있다. 복원이 그것을 "\
"지운다. 먼저 \`wip:\` 커밋을 하라(규율 9)."
  exit 2
fi

printf "  %-5s %-42s → " "$NAME" "$WHY"

# ② 돌연변이를 넣는다
if ! perl -0pi -e "$EDIT" "$FILE"; then
  print -r -- "🔴 perl 이 실패했다"; exit 2
fi

# ══════════════════════════════════════════════════════════════════
# 🔴 ③ **치환이 먹었나**(규율 8) — 안 먹었으면 "통과"가 거짓이다
# ══════════════════════════════════════════════════════════════════
if git diff --quiet -- "$FILE"; then
  print -r -- "🔴 치환이 **빗나갔다** — 바뀐 줄이 없다. 돌연변이가 아니다"
  exit 3
fi

# ④ 돌린다. 🔴 `__pycache__` 는 conftest 가 스위트 시작 전에 지운다
RESULT=$(PYTHONPATH=. uv run pytest "${TESTS[@]}" -q 2>&1 | tail -1)

# ══════════════════════════════════════════════════════════════════
# 🔴 ⑤ **복원 — `git checkout`** 하고 **깨끗한지 확인**한다
# ══════════════════════════════════════════════════════════════════
git checkout -- "$FILE"
if ! git diff --quiet -- "$FILE"; then
  print -r -- "🔴🔴 **복원 실패** — \`$FILE\` 이 아직 다르다. 멈춰라"
  exit 4
fi

print -r -- "$RESULT"
# 🔴 돌연변이는 **빨개야** 한다 — 초록이면 그 계약은 **없는 것**이다(§9-5)
[[ "$RESULT" == *failed* ]] || { print -r -- \
  "     🔴🔴 **$NAME 이 통과했다** — §9-5: 통과하는 돌연변이는 계약이 없다는 뜻이다"
  exit 1; }
